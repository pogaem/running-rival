// 상대의 화면용 별명 (사용자 요청: 번호 대신 캐릭터 이름)
// 내부 이름표(가상러너-03 등)는 저장·매칭에 그대로 쓰고, 화면에만 별명을 보여 준다.
// 별명은 실제 사람 이름이 아니라 달리는 모양을 딴 캐릭터 이름이다. "가상 러너" 표시는 화면에 그대로 남긴다.
const NICKNAMES: Record<string, string> = {
  "가상러너-01": "철벽 시계추",
  "가상러너-02": "막판 번개",
  "가상러너-03": "새벽 질주왕",
  "가상러너-04": "뒷심 여우",
  "가상러너-05": "중반 거북",
  "가상러너-06": "초반 토끼",
  "가상러너-07": "끝판 해결사",
  "가상러너-08": "느긋한 산책러",
  "가상러너-09": "꾸준한 곰",
};

/** 화면에 보여 줄 이름. 별명이 없으면(캠프 참가자 등) 이름표 그대로 */
export function displayName(id: string): string {
  return NICKNAMES[id] ?? id;
}
